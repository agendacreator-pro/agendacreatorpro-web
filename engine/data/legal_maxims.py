def obter_maximas(categoria=None):
    """Retorna lista de dicts {id, texto, traducao, categoria}."""
    if categoria:
        return [m for m in obter_todas() if m["categoria"] == categoria]
    return obter_todas()


def obter_todas():
    return [
        {
            "id": i,
            "texto": texto,
            "traducao": traducao,
            "categoria": categoria,
        }
        for i, (texto, traducao, categoria) in enumerate(_BROCARDOS, start=1)
    ]


def obter_maxima_por_id(maxima_id):
    for m in obter_todas():
        if m["id"] == maxima_id:
            return m
    return None


def obter_maxima_do_dia(dia_do_ano):
    todas = obter_todas()
    return todas[(dia_do_ano - 1) % len(todas)]


